export type RaceId = 'human' | 'magic' | 'monster'
export type Difficulty = 'easy' | 'normal' | 'hard'

export interface Cost {
  wood: number
  gold: number
  iron: number
}

export type UnitRole = 'worker' | 'melee' | 'ranged' | 'caster' | 'giant' | 'air'
export type UnitShape = 'circle' | 'square' | 'triangle' | 'diamond' | 'star'

export interface UnitDef {
  id: string
  name: string
  cost: Cost
  hp: number
  damage: number
  range: number
  speed: number
  attackInterval: number
  role: UnitRole
  flying: boolean
  canHitAir: boolean
  camouflage: boolean
  cone: boolean
  splash: number
  plantCooldown: number
  plantDuration: number
  healer: boolean
  dark: boolean
  bonusVsPlant: boolean
  hotkey: string
  radius: number
  scale: number
  supply: number
  trainTime: number
  color: number
  shape: UnitShape
  weapon: string
  blurb: string
}

export interface BuildingDef {
  id: string
  name: string
  cost: Cost
  hp: number
  trains: string[]
  supplyBonus: number
  dropoff: boolean
  mineShaft: boolean
  buildable: boolean
  hotkey: string
  tilesW: number
  tilesH: number
  buildTime: number
  color: number
  blurb: string
  upgradeTo?: string
  upgradeCost?: Cost
  upgradeHotkey?: string
}


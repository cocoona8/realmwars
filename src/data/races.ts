export const RACES: Record<RaceId, RaceDef> = {
  human: humans,
  magic,
  monster: monsters,
}

export const RACE_IDS: RaceId[] = ['human', 'magic', 'monster']

export function getRace(id: RaceId): RaceDef {
  return RACES[id]
}

export function getUnitDef(race: RaceId, id: string): UnitDef {
  const unit = RACES[race].units.find((entry) => entry.id === id)
  if (!unit) throw new Error(`Missing unit ${race}/${id}`)
  return unit
}

export function getBuildingDef(race: RaceId, id: string): BuildingDef {
  const building = RACES[race].buildings.find((entry) => entry.id === id)
  if (!building) throw new Error(`Missing building ${race}/${id}`)
  return building
}

export function canAfford(have: Cost, price: Cost): boolean {
  return have.wood >= price.wood && have.gold >= price.gold && have.iron >= price.iron
}

export function pay(have: Cost, price: Cost): void {
  have.wood -= price.wood
  have.gold -= price.gold
  have.iron -= price.iron
}

export function refund(have: Cost, price: Cost): void {
  have.wood += price.wood
  have.gold += price.gold
  have.iron += price.iron
}

export function costLabel(price: Cost): string {
  const parts: string[] = []
  if (price.wood) parts.push(`${price.wood} wood`)
  if (price.gold) parts.push(`${price.gold} gold`)
  if (price.iron) parts.push(`${price.iron} iron`)
  return parts.join(', ') || 'Free'
}

export function missingResource(have: Cost, price: Cost): string | null {
  if (have.wood < price.wood) return 'Not enough wood.'
  if (have.gold < price.gold) return 'Not enough gold.'
  if (have.iron < price.iron) return 'Not enough iron.'
  return null
}
